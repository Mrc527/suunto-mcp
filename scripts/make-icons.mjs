#!/usr/bin/env node
// Turn the logo (assets/brand/logo.svg, and logo-small.svg for 16-32 px) into the icons the web
// service serves: favicon.ico, PNGs for apps and the MCP serverInfo, and the SVG itself.
// Writes src/web/brand-assets.ts and docs/directory/icon-512.png (the icon for directory
// listings). Run it after changing the logo:
//
//   node scripts/make-icons.mjs
//
// Needs Playwright with Chromium (only for this script, not for the server). With a global
// Playwright install, run it as: NODE_PATH="$(npm root -g)" node scripts/make-icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");

const root = new URL("..", import.meta.url);
const logo = readFileSync(new URL("assets/brand/logo.svg", root), "utf8").trim();
const small = readFileSync(new URL("assets/brand/logo-small.svg", root), "utf8").trim();

const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 1 });

async function png(svg, size) {
  await page.setViewportSize({ width: size, height: size });
  const sized = svg.replace(/<svg\b[^>]*>/, (tag) => tag.replace(/\s(width|height)="[^"]*"/g, "").replace(/>$/, ` width="${size}" height="${size}">`));
  await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent">${sized}</body></html>`);
  return page.locator("svg").first().screenshot({ omitBackground: true, type: "png" });
}

const sizes = { 16: small, 32: small, 48: logo, 180: logo, 192: logo };
const pngs = {};
for (const [size, svg] of Object.entries(sizes)) pngs[size] = await png(svg, Number(size));
const directoryIcon = await png(logo, 512);
await browser.close();

// favicon.ico with PNG images (supported by every current browser).
function ico(images) {
  const header = Buffer.alloc(6 + 16 * images.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(([size, data], i) => {
    const e = 6 + 16 * i;
    header.writeUInt8(size >= 256 ? 0 : size, e);
    header.writeUInt8(size >= 256 ? 0 : size, e + 1);
    header.writeUInt8(0, e + 2);
    header.writeUInt8(0, e + 3);
    header.writeUInt16LE(1, e + 4);
    header.writeUInt16LE(32, e + 6);
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map(([, d]) => d)]);
}
const favicon = ico([16, 32, 48].map((s) => [s, pngs[s]]));

const b64 = (buf) => buf.toString("base64");
const out = `/**
 * The app's logo and icons. Generated by scripts/make-icons.mjs from assets/brand/*.svg: do not
 * edit by hand.
 */

/** The logo as SVG (full size, rounded tile). */
export const LOGO_SVG = ${JSON.stringify(logo)};

/** The simplified logo for 16-32 px. */
export const LOGO_SMALL_SVG = ${JSON.stringify(small)};

/** favicon.ico (16, 32 and 48 px). */
export const FAVICON_ICO = Buffer.from(${JSON.stringify(b64(favicon))}, "base64");

/** PNG icons by size in pixels. */
export const ICON_PNG: Record<number, Buffer> = {
${Object.entries(pngs)
  .map(([s, d]) => `  ${s}: Buffer.from(${JSON.stringify(b64(d))}, "base64"),`)
  .join("\n")}
};
`;
writeFileSync(new URL("src/web/brand-assets.ts", root), out);
console.log(`Wrote src/web/brand-assets.ts (${Math.round(out.length / 1024)} KB)`);
writeFileSync(new URL("docs/directory/icon-512.png", root), directoryIcon);
console.log(`Wrote docs/directory/icon-512.png (${Math.round(directoryIcon.length / 1024)} KB)`);
